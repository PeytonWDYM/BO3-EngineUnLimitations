def prepare_physics_state(code: CapturedCode) -> tuple[Rewrite, ...]:
    """Use native sizing, allocation, initialization, and teardown. Replace only fixed-width row operands."""
    if code.executable_sha256 != EXECUTABLE_SHA256:
        raise ValueError('The physics state banks require the exact admitted executable.')
    for guard in GUARDS:
        code.guarded(guard)
    # Runtime generation admits all 25 table pointers after actual-image ASLR normalization.
    actual = struct.unpack('<25Q', code.read(0x33C28F0, 200))
    expected = tuple(code.base + target for row in DISPATCH_TARGETS for target in row)
    if actual != expected:
        raise ValueError('The native physics allocator dispatch bindings differ.')
    edits = []
    for name, rva, original_hex, replacement_hex in SITES:
        original, replacement = bytes.fromhex(original_hex), bytes.fromhex(replacement_hex)
        if code.read(rva, len(original)) != original:
            raise ValueError('A native physics row instruction differs.')
        edits.append(Rewrite(name, code.guard(rva, len(original)), replacement))
    return tuple(edits)
